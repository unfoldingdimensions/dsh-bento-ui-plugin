// Concatenate src/NN-*.js fragments into the single browser bundle.
// Zero dependencies: the host serves one pre-built client.js per package, so the
// bundle is assembled here rather than at runtime.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const srcDir = join(root, 'src');

const fragments = readdirSync(srcDir)
  .filter((name) => name.endsWith('.js'))
  .sort();

const body = fragments
  .map((name) => {
    const text = readFileSync(join(srcDir, name), 'utf8').replace(/\s+$/, '');
    return `//#region src/${name}\n${text}\n//#endregion`;
  })
  .join('\n\n');

const banner = `// Generated by build.mjs from src/*.js — do not edit this file directly.\n`;

// The bundle stays at the package root: the host's client module roster
// resolves `dsh.client` / `./client` at boot, and the shipped template uses this
// exact path. Moving it under lib/ leaves the running app pointing at a file
// that no longer exists.
const outFile = join(root, 'client.js');
writeFileSync(outFile, `${banner}${body}\n`);
console.log(`built ${outFile} from ${fragments.length} fragments (${body.length} bytes)`);
