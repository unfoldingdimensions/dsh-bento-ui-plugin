// Generate src/14-fontdata.js from assets/*.woff2.
//
// WHY EMBEDDED, AND NOT A SERVED FILE
// The host serves a plugin's browser half through one concatenating module route
// (`/plugins/??<pkg>/client.js&rev=…`). Probed directly: every other path shape for a
// package file — icon.svg, package.json, a fonts/ directory — answers 404, so there is
// no static route this package can hang a .woff2 on. The two ways to deliver a real file
// would be a host-side route (dsh-claude-style does this) or a data: URI.
//
// A host route was rejected on this plugin's own architecture rule: index.js documents
// that its host half is deliberately inert because work at activation turns any mistake
// into a whole-application boot failure. Adding a font route means host code, a route
// table, and a failure mode on the boot path — all to serve 88 KB.
//
// So the bytes travel inside the bundle as base64. The cost is honest and bounded:
// ~118 KB of source, ~118 KB added to client.js, paid once at module load, on loopback.
// The decided cost is recorded in decision.md (D59).
//
// The gate `source: no hardcoded colour` scans src/*.js. A base64 blob is not a colour
// declaration, but it could contain the letters of one, so that gate excludes this one
// generated file by name rather than going blind to a directory.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assets = join(root, 'assets');

const INTER = readFileSync(join(assets, 'inter-latin.woff2')).toString('base64');
const MONO = readFileSync(join(assets, 'jetbrains-mono-latin.woff2')).toString('base64');

const header = `/**
 * GENERATED by tools/make-fontdata.mjs — do not edit.
 *
 * The two typefaces the reference design specifies, latin subset only, variable weight
 * axis, base64 inside the bundle. See that script for why they are embedded rather than
 * served, and decision.md D59 for the cost that was accepted.
 *
 * Both are OFL 1.1; the licences ship beside them in assets/.
 */
`;

const body = `    /** Inter, latin subset, wght 100-900. ${Math.round(INTER.length * 0.75 / 1024)} KB decoded. */
    const FONT_INTER_WOFF2 = '${INTER}';
    /** JetBrains Mono, latin subset, wght 100-800. ${Math.round(MONO.length * 0.75 / 1024)} KB decoded. */
    const FONT_MONO_WOFF2 = '${MONO}';
`;

writeFileSync(join(root, 'src', '14-fontdata.js'), `${header}${body}`);
console.log(`wrote src/14-fontdata.js — inter ${INTER.length} b64 chars, mono ${MONO.length} b64 chars`);
